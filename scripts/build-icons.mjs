// Bundles public/icons/ui-*.svg into public/icons.css as data URIs, so drawing an icon never
// starts a network request (each first-time mask-image fetch would flash the browser's loading indicator).
// Run after adding an icon: node scripts/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const dir = path.join(ROOT, 'public', 'icons');
const files = fs.readdirSync(dir).filter((f) => /^ui-.+\.svg$/.test(f)).sort();
let css = '/* Generated by scripts/build-icons.mjs. Do not edit. */\n';
for (const f of files) {
  const name = f.slice(3, -4);
  const svg = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\s+/g, ' ').trim();
  css += `.i-${name}{--i:url("data:image/svg+xml,${encodeURIComponent(svg)}")}\n`;
}
fs.writeFileSync(path.join(ROOT, 'public', 'icons.css'), css);
console.log(`icons.css: ${files.length} icons, ${css.length} bytes`);
